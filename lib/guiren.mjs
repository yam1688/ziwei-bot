const TY = {
  甲:{z:['丑','未'],x:['牛','羊'],d:['东北','西南']}, 乙:{z:['子','申'],x:['鼠','猴'],d:['正北','西南']},
  丙:{z:['亥','酉'],x:['猪','鸡'],d:['西北','正西']}, 丁:{z:['亥','酉'],x:['猪','鸡'],d:['西北','正西']},
  戊:{z:['丑','未'],x:['牛','羊'],d:['东北','西南']}, 己:{z:['子','申'],x:['鼠','猴'],d:['正北','西南']},
  庚:{z:['丑','未'],x:['牛','羊'],d:['东北','西南']}, 辛:{z:['午','寅'],x:['马','虎'],d:['正南','东北']},
  壬:{z:['巳','卯'],x:['蛇','兔'],d:['东南','正东']}, 癸:{z:['巳','卯'],x:['蛇','兔'],d:['东南','正东']},
};
const SX = ['鼠','牛','虎','兔','龙','蛇','马','羊','猴','鸡','狗','猪'];
export function genGuiRenText(gan, by){
  const i = TY[gan]; if(!i) return '';
  const sx = SX[by%12];
  let r = '🙏 **天乙贵人**\n  年干'+gan+'→贵人在'+i.z.join('、')+'方（'+i.d.join('、')+'）\n  贵人属相：'+i.x.join('、')+'\n';
  if(i.x.includes(sx)) r+='  你本人就是贵人！属'+sx+'与天乙贵人同属，自带贵人气质。\n';
  else r+='  属'+sx+'者与'+i.x.join('、')+'属相交往可得助益。\n';
  r+='  贵人方位：办公桌朝'+i.d[0]+'，多往'+i.d.join('、')+'方出行\n';
  return r+'\n';
}
