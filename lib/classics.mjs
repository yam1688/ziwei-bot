const CLASSIC_NAMES = Object.keys(CLASSICS);

const MD_ESC = { "_":"\\_","*":"\\*","`":"\\`","[":"\\[" };
function escMD(s) { return String(s).replace(/[_*\`\[\]]/g, c => MD_ESC[c] || c); }

export function genClassics(name) {
  if (!name || !CLASSICS[name]) {
    let r = `📜 **紫微斗数古籍**\n━━━━━━━━━━━━━━\n\n可用书目：\n`;
    for (const n of CLASSIC_NAMES) {
      r += `  📖 ${n}（${CLASSICS[n].length} 条）\n`;
    }
    r += `\n查看详情：/guji 骨髓赋`;
    return r;
  }
  
  const verses = CLASSICS[name];
  let r = `📜 **${name}**\n━━━━━━━━━━━━━━\n\n`;
  for (const v of verses) {
    r += `  ${escMD(v)}\n\n`;
  }
  return r;
}

export { CLASSIC_NAMES };
